"""Deterministic closed-package emission and trusted stable dispatcher bundling.

No execution of retained shell source. No external build tool or runtime imports.
The standalone bootstrap is generated by bootstrap_bytes(), from these sources.
"""
import ast
import os
from pathlib import Path
from .safe import exclusive, need, physical, sha
from .package import DIRS, LEAVES, ROLES, package_header, payload_mode, verify_package
from .factories import PROVIDERS, factory

SOURCE = Path(__file__).resolve().parent


def bundle(names):
    parts = []
    for name in names:
        text = (SOURCE / (name + ".py")).read_text()
        lines = text.splitlines(keepends=True)
        imports = [(n.lineno, n.end_lineno) for n in ast.parse(text).body
                   if isinstance(n, ast.ImportFrom) and n.level]
        parts.append("".join(line for i, line in enumerate(lines, 1)
                             if not any(start <= i <= end for start, end in imports)))
    result = "\n".join(parts)
    compile(result, "<trusted-v2-bundle>", "exec")
    return result


def python_shell(program):
    # -I -S -B: no cwd/site/user imports, environment startup or bytecode writes.
    return ("#!/bin/bash -p\nset -eu\ncommand -v python3 >/dev/null 2>&1 || exit 1\n"
            "if [ \"$(command -v python3)\" = /usr/bin/python3 ] && "
            "[ \"$(uname -s)\" = Darwin ]; then exit 1; fi\n"
            "exec python3 -I -S -B - \"$@\" <<'DOMESTIQUE_V2_TRUSTED_PY'\n" +
            "import sys\nif sys.version_info < (3, 9): sys.exit(1)\n" +
            program + "\nDOMESTIQUE_V2_TRUSTED_PY\n").encode()


def dispatcher_program():
    return bundle(("safe", "package", "records", "cli", "dispatcher"))


def launcher_bytes(root, home):
    return python_shell(dispatcher_program() +
                        f"\nsys.exit(dispatch_main({str(root)!r}, {str(home)!r}))\n")


def inspector_source():
    # Exact retained engine, not the old shell parser, writer or workflow body.
    source = (SOURCE.parent / "domestique2.sh").read_text()
    start = "<<'DOM_INSPECT_PY' || inspect_rc=$?\n"
    need(source.count(start) == 1, "inspector source boundary")
    return source.split(start, 1)[1].split("\nDOM_INSPECT_PY\n", 1)[0]


def management_bytes():
    return python_shell(bundle(("safe", "package", "cli", "management")) +
                        f"\nsys.exit(management_main({inspector_source()!r}))\n")


def bootstrap_bytes():
    # Use the EXACT builder functions, not an independently maintained renderer.
    source = (SOURCE / "build.py").read_text()
    nodes = ast.parse(source).body
    functions = "\n".join(ast.get_source_segment(source, n) for n in nodes
                          if isinstance(n, ast.FunctionDef) and
                          n.name in ("python_shell", "launcher_bytes"))
    rendering = (f"\ndef dispatcher_program():\n    return {dispatcher_program()!r}\n" +
                 functions)
    program = bundle(("safe", "package", "records", "journal", "runtime", "cli"))
    program += rendering + "\n" + bundle(("publisher", "transport", "bootstrap"))
    return python_shell(program + "\nsys.exit(bootstrap_main())\n")


def package_data(version):
    refusal = (b"#!/bin/bash\n"
               b"printf '%s\\n' 'domestique2: unsupported; activation/management unavailable' >&2\n"
               b"exit 1\n")
    data = {"PACKAGE": package_header(version),
            "domestique2.sh": management_bytes(), "update2.sh": refusal,
            # No bind/read/route/bootstrap/Beads old-policy bypass.
            "bin/resolve-core": refusal}
    for role in ROLES:
        data["roles/" + role + ".md"] = (SOURCE / "roles" / (role + ".md")).read_bytes()
    for provider in PROVIDERS:
        data["adapters/" + provider + ".templates"] = factory(provider)
    data["SHA256SUMS"] = b"".join((sha(data[p]) + "  " + p + "\n").encode()
                                  for p in sorted(data))
    need(tuple(sorted(data)) == LEAVES, "build inventory")
    return data


def emit_package(destination, version):
    """Exclusively emit a local development package; caller owns output parent."""
    destination = physical(destination)
    need(not destination.exists(), "package output collision")
    data = package_data(version)
    os.mkdir(destination, 0o700)
    for d in DIRS:
        os.mkdir(destination / d, 0o700)
    for p in LEAVES:
        exclusive(destination / p, data[p], payload_mode(p))
    return verify_package(destination, version, installed=True)


def emit_bootstrap(destination):
    """Generate a NEW standalone artifact; never overwrite an existing file."""
    exclusive(physical(destination), bootstrap_bytes(), 0o755)


if __name__ == "__main__":
    import sys
    need(len(sys.argv) == 2, "usage: python3 -B -m v2.build NEW_BOOTSTRAP_PATH")
    emit_bootstrap(str(Path(sys.argv[1]).absolute()))
